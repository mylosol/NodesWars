// Generates src/decayTable.ts: 2^(-i/64) in Fixed (scale 2^16), i = 0..64.
//
// Fortify shields decay on a half-life. The whole number of half-lives is a
// bit shift; this table covers the fractional remainder, which keeps the
// runtime free of Math.pow and identical between the TS and PHP engines.
//
// Run: node scripts/gen-decay-table.mjs > src/decayTable.ts

const STEPS = 64;
const SCALE = 65536;

const values = [];
for (let i = 0; i <= STEPS; i++) {
  values.push(Math.round(Math.pow(2, -i / STEPS) * SCALE));
}

const rows = [];
for (let i = 0; i < values.length; i += 8) {
  rows.push('  ' + values.slice(i, i + 8).join(', ') + ',');
}

process.stdout.write(`// GENERATED by scripts/gen-decay-table.mjs. Do not edit by hand.
//
// DECAY_TABLE[i] = round(2^(-i/${STEPS}) * ${SCALE}), for i in 0..${STEPS}.
// Index 0 is 1.0 and index ${STEPS} is exactly 0.5.

export const DECAY_STEPS = ${STEPS};

export const DECAY_TABLE: readonly number[] = [
${rows.join('\n')}
];
`);
