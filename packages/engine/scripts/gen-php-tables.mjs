// Emits the PHP copies of the lookup tables from the committed TypeScript ones.
//
// Deliberately re-reads the generated .ts files rather than recomputing from
// the formula. Recomputing would give two sources of truth that could drift;
// this way the PHP table is identical to the TypeScript table by construction.
//
// Run from packages/engine: node scripts/gen-php-tables.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

function readNumbers(tsPath, constName) {
  const src = readFileSync(here(tsPath), 'utf8');
  const match = new RegExp(`${constName}[^=]*=\\s*\\[([^\\]]*)\\]`, 's').exec(src);
  if (!match) throw new Error(`could not find ${constName} in ${tsPath}`);
  const values = match[1]
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
    .map((s) => {
      const n = Number(s);
      if (!Number.isInteger(n)) throw new Error(`non-integer entry ${s} in ${constName}`);
      return n;
    });
  if (values.length === 0) throw new Error(`${constName} parsed as empty`);
  return values;
}

function phpFile({ className, constName, values, doc }) {
  const rows = [];
  for (let i = 0; i < values.length; i += 8) {
    rows.push('        ' + values.slice(i, i + 8).join(', ') + ',');
  }
  return `<?php

declare(strict_types=1);

namespace NodesWars\\Api\\Engine;

/**
 * GENERATED by packages/engine/scripts/gen-php-tables.mjs. Do not edit by hand.
 *
 * ${doc}
 */
final class ${className}
{
    /** @var list<int> */
    public const ${constName} = [
${rows.join('\n')}
    ];
}
`;
}

const targets = [
  {
    ts: '../src/sineTable.ts',
    tsConst: 'SINE_TABLE',
    className: 'SineTable',
    constName: 'VALUES',
    out: '../../../apps/api/src/Engine/SineTable.php',
    doc: 'Mirror of packages/engine/src/sineTable.ts: sine at 1/16 degree resolution, scaled by 2^16.',
  },
  {
    ts: '../src/decayTable.ts',
    tsConst: 'DECAY_TABLE',
    className: 'DecayTable',
    constName: 'VALUES',
    out: '../../../apps/api/src/Engine/DecayTable.php',
    doc: 'Mirror of packages/engine/src/decayTable.ts: 2^(-i/64) scaled by 2^16.',
  },
];

for (const t of targets) {
  const values = readNumbers(t.ts, t.tsConst);
  writeFileSync(here(t.out), phpFile({ ...t, values }));
  console.log(`${t.className}.php: ${values.length} entries`);
}
